-- Ejecutar una vez en un worksheet de Snowflake con el rol ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS PSET2_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS PSET2_MORA;
CREATE SCHEMA IF NOT EXISTS PSET2_MORA.RAW;
CREATE SCHEMA IF NOT EXISTS PSET2_MORA.BRONZE;
CREATE SCHEMA IF NOT EXISTS PSET2_MORA.SILVER;
CREATE SCHEMA IF NOT EXISTS PSET2_MORA.GOLD;
CREATE SCHEMA IF NOT EXISTS PSET2_MORA.OBT;

CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT ROLE PSET2_ROLE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT OWNERSHIP ON DATABASE PSET2_MORA TO ROLE PSET2_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE PSET2_MORA TO ROLE PSET2_ROLE COPY CURRENT GRANTS;

-- Usuario de servicio con autenticación key-pair (sin contraseña).
-- Pega la llave PÚBLICA sin las líneas BEGIN/END ni saltos de línea.
CREATE USER IF NOT EXISTS PSET2_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE
  DEFAULT_WAREHOUSE = PSET2_WH
  RSA_PUBLIC_KEY = '<PEGA_AQUI_TU_LLAVE_PUBLICA>';
GRANT ROLE PSET2_ROLE TO USER PSET2_SVC;
